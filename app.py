import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import streamlit as st
3
st.title("Visualización de Datos: Matplotlib vs Seaborn")

np.random.seed(42)
dias = ['Lun', 'Mar', 'Mié', 'Jue', 'Vie', 'Sáb', 'Dom']

df = pd.DataFrame({
    'Día': dias,
    'Ventas': [150, 220, 180, 290, 310, 400, 350],
    'Gastos': [80, 120, 100, 150, 160, 210, 190]
})

df_scatter = pd.DataFrame({
    'Horas_Estudio': np.random.randint(1, 10, size=40),
    'Nota_Examen': np.random.randint(40, 100, size=40)
})

datos_hist = np.random.normal(loc=70, scale=10, size=150)

# 1. GRÁFICO DE LÍNEAS
st.header("1. Gráfico de Líneas")
col1, col2 = st.columns(2)
with col1:
    st.subheader("Matplotlib")
    fig, ax = plt.subplots(figsize=(5, 3.5))
    ax.plot(df['Día'], df['Ventas'], marker='o', color='tab:blue')
    ax.set_title("Ventas por Día")
    ax.grid(True, linestyle='--', alpha=0.6)
    st.pyplot(fig)

with col2:
    st.subheader("Seaborn")
    fig, ax = plt.subplots(figsize=(5, 3.5))
    sns.lineplot(data=df, x='Día', y='Ventas', marker='o', color='teal', ax=ax)
    ax.set_title("Ventas por Día")
    st.pyplot(fig)

# 2. GRÁFICO DE BARRAS
st.header("2. Gráfico de Barras")
col1, col2 = st.columns(2)
with col1:
    st.subheader("Matplotlib")
    fig, ax = plt.subplots(figsize=(5, 3.5))
    x = np.arange(len(df['Día']))
    ancho = 0.35
    ax.bar(x - ancho/2, df['Ventas'], ancho, label='Ventas', color='skyblue')
    ax.bar(x + ancho/2, df['Gastos'], ancho, label='Gastos', color='salmon')
    ax.set_xticks(x)
    ax.set_xticklabels(df['Día'])
    ax.set_title("Ventas vs Gastos")
    ax.legend()
    st.pyplot(fig)

with col2:
    st.subheader("Seaborn")
    fig, ax = plt.subplots(figsize=(5, 3.5))
    df_melted = df.melt(id_vars=['Día'], value_vars=['Ventas', 'Gastos'], var_name='Concepto', value_name='Monto')
    sns.barplot(data=df_melted, x='Día', y='Monto', hue='Concepto', palette='Set2', ax=ax)
    ax.set_title("Ventas vs Gastos")
    st.pyplot(fig)

# 3. GRÁFICO DE DISPERSIÓN
st.header("3. Gráfico de Dispersión")
col1, col2 = st.columns(2)
with col1:
    st.subheader("Matplotlib")
    fig, ax = plt.subplots(figsize=(5, 3.5))
    ax.scatter(df_scatter['Horas_Estudio'], df_scatter['Nota_Examen'], color='purple', alpha=0.7)
    ax.set_title("Horas vs Nota")
    ax.grid(True, linestyle='--', alpha=0.5)
    st.pyplot(fig)

with col2:
    st.subheader("Seaborn")
    fig, ax = plt.subplots(figsize=(5, 3.5))
    sns.scatterplot(data=df_scatter, x='Horas_Estudio', y='Nota_Examen', color='purple', ax=ax)
    ax.set_title("Horas vs Nota")
    st.pyplot(fig)

# 4. HISTOGRAMA
st.header("4. Histograma")
col1, col2 = st.columns(2)
with col1:
    st.subheader("Matplotlib")
    fig, ax = plt.subplots(figsize=(5, 3.5))
    ax.hist(datos_hist, bins=12, color='orange', edgecolor='black', alpha=0.7)
    ax.set_title("Distribución de Notas")
    st.pyplot(fig)

with col2:
    st.subheader("Seaborn")
    fig, ax = plt.subplots(figsize=(5, 3.5))
    sns.histplot(datos_hist, bins=12, color='orange', kde=True, ax=ax)
    ax.set_title("Distribución con KDE")
    st.pyplot(fig)

# 5. DIAGRAMA DE CAJA
st.header("5. Diagrama de Caja")
col1, col2 = st.columns(2)
with col1:
    st.subheader("Matplotlib")
    fig, ax = plt.subplots(figsize=(5, 3.5))
    ax.boxplot(df['Ventas'], patch_artist=True, boxprops=dict(facecolor='lightgreen'))
    ax.set_title("Resumen de Ventas")
    st.pyplot(fig)

with col2:
    st.subheader("Seaborn")
    fig, ax = plt.subplots(figsize=(5, 3.5))
    sns.boxplot(y=df['Ventas'], color='lightgreen', ax=ax)
    ax.set_title("Resumen de Ventas")
    st.pyplot(fig)