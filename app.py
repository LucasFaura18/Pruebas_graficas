import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Configuración de datos de ejemplo
np.random.seed(42)
dias = ['Lun', 'Mar', 'Mié', 'Jue', 'Vie', 'Sáb', 'Dom']

df = pd.DataFrame({
    'Día': dias,
    'Ventas': [150, 220, 180, 290, 310, 400, 350],
    'Gastos': [80, 120, 100, 150, 160, 210, 190]
})

df_scatter = pd.DataFrame({
    'Horas_Estudio': np.random.randint(1, 10, size=40),
    'Nota_Examen': np.random.randint(40, 100, size=40)
})

datos_hist = np.random.normal(loc=70, scale=10, size=150)

# 1. GRÁFICO DE LÍNEAS (Evolución de Ventas)

# Matplotlib
plt.figure(figsize=(7, 4))
plt.plot(df['Día'], df['Ventas'], marker='o', color='tab:blue', label='Ventas')
plt.title("1A. Gráfico de Líneas - Matplotlib")
plt.xlabel("Día")
plt.ylabel("Ventas ($)")
plt.grid(True, linestyle='--', alpha=0.6)
plt.show()

# Seaborn
plt.figure(figsize=(7, 4))
sns.lineplot(data=df, x='Día', y='Ventas', marker='o', color='teal')
plt.title("1B. Gráfico de Líneas - Seaborn")
plt.xlabel("Día")
plt.ylabel("Ventas ($)")
plt.show()

# 2. GRÁFICO DE BARRAS (Ventas vs Gastos)

# Matplotlib
plt.figure(figsize=(7, 4))
x = np.arange(len(df['Día']))
ancho = 0.35
plt.bar(x - ancho/2, df['Ventas'], ancho, label='Ventas', color='skyblue')
plt.bar(x + ancho/2, df['Gastos'], ancho, label='Gastos', color='salmon')
plt.xticks(x, df['Día'])
plt.title("2A. Gráfico de Barras Agrupadas - Matplotlib")
plt.xlabel("Día")
plt.ylabel("Monto ($)")
plt.legend()
plt.show()

# Seaborn
plt.figure(figsize=(7, 4))
df_melted = df.melt(id_vars=['Día'], value_vars=['Ventas', 'Gastos'], var_name='Concepto', value_name='Monto')
sns.barplot(data=df_melted, x='Día', y='Monto', hue='Concepto', palette='Set2')
plt.title("2B. Gráfico de Barras Agrupadas - Seaborn")
plt.show()

# 3. GRÁFICO DE DISPERSIÓN (Scatter Plot)

# Matplotlib
plt.figure(figsize=(7, 4))
plt.scatter(df_scatter['Horas_Estudio'], df_scatter['Nota_Examen'], color='purple', alpha=0.7)
plt.title("3A. Dispersión Horas vs Nota - Matplotlib")
plt.xlabel("Horas de Estudio")
plt.ylabel("Nota Final")
plt.grid(True, linestyle='--', alpha=0.5)
plt.show()

# Seaborn
plt.figure(figsize=(7, 4))
sns.scatterplot(data=df_scatter, x='Horas_Estudio', y='Nota_Examen', color='purple')
plt.title("3B. Dispersión Horas vs Nota - Seaborn")
plt.xlabel("Horas de Estudio")
plt.ylabel("Nota Final")
plt.show()

# 4. HISTOGRAMA (Distribución)

# Matplotlib
plt.figure(figsize=(7, 4))
plt.hist(datos_hist, bins=12, color='orange', edgecolor='black', alpha=0.7)
plt.title("4A. Histograma de Notas - Matplotlib")
plt.xlabel("Notas")
plt.ylabel("Frecuencia")
plt.show()

# Seaborn
plt.figure(figsize=(7, 4))
sns.histplot(datos_hist, bins=12, color='orange', kde=True)
plt.title("4B. Histograma con Estimación de Densidad (KDE) - Seaborn")
plt.xlabel("Notas")
plt.ylabel("Frecuencia")
plt.show()

# 5. DIAGRAMA DE CAJA (Boxplot)

# Matplotlib
plt.figure(figsize=(7, 4))
plt.boxplot(df['Ventas'], patch_artist=True, boxprops=dict(facecolor='lightgreen'))
plt.title("5A. Diagrama de Caja de Ventas - Matplotlib")
plt.ylabel("Ventas ($)")
plt.xticks([1], ['Ventas'])
plt.show()

# Seaborn
plt.figure(figsize=(7, 4))
sns.boxplot(y=df['Ventas'], color='lightgreen')
plt.title("5B. Diagrama de Caja de Ventas - Seaborn")
plt.ylabel("Ventas ($)")
plt.show()
